create or replace FUNCTION get_average_rating(
    p_product_id IN NUMBER
) RETURN NUMBER IS
    v_avg NUMBER;
BEGIN
    SELECT ROUND(AVG(RATING), 2)
      INTO v_avg
      FROM FEEDBACK
     WHERE PRODUCTID = p_product_id;
    RETURN NVL(v_avg, 0);
EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN 0;
    WHEN OTHERS THEN RETURN NULL;
END;
